/**
 * Every committed brand asset, declared once.
 *
 * The generator (`scripts/build-brand.mjs`) writes this list, `npm run
 * brand:check` verifies it, and `tests/brand.test.ts` asserts the files still
 * match. Declaring the set here rather than inside the script is what stops the
 * check from being "the generator agrees with itself": a variant that is added
 * to the generator but not to the docs, or vice versa, is a visible diff.
 *
 * File names carry the ink rather than a vague "variant": `mark-ink.svg` is
 * `--ink` on transparency, `mark-compact-canvas.svg` is the icon form in
 * `--canvas`. An asset whose name does not say which ink it is drawn in is an
 * asset somebody has to open to use.
 */
import { MARK_INK, MARK_MIN_SIZE_PX, type MarkDetail } from "./mark.ts";

export interface BrandSvgAsset {
	/** Repository-relative path. */
	file: string;
	/** `aria-label`, and the sentence used in the docs table. */
	label: string;
	/**
	 * `mark` is generated by `markSvg()`. `diagram` is generated by
	 * `clearSpaceSvg()`, which is a document rather than a placement asset and
	 * reads its numbers from the constants instead of taking them as arguments.
	 */
	kind?: "mark" | "diagram";
	detail: MarkDetail;
	ink: string;
	ground?: string;
	/** Intrinsic size; omitted so a kit file scales freely. */
	size?: number;
	/** Held inside Android's maskable safe zone. */
	maskable?: boolean;
	/** Where the variant is meant to be used. Kept short — this is a usage note, not a paragraph. */
	used: string;
}

