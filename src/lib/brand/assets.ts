/**
 * Android's maskable safe zone is the circle of diameter 80% of the icon, so a
 * mark drawn edge to edge is cropped by every launcher that masks. The icon
 * form is scaled to 80% of the box and centred, which puts its outermost ink
 * inside that circle with room to spare.
 */
export const MASKABLE_SCALE = 0.8;

/**
 * Smallest size the *full* form is drawn at, re-exported so the manifest and
 * the docs table read the same number the geometry does.
 */
